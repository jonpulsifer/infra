#!/usr/bin/env bash
# Renders clusters/folly/inventory/machines.yaml from NetBox: every folly device with the role
# kubernetes-node and the status planned, staged, active or failed, ordered by address. A device
# with no serial, no MAC or no talos_class is left out, whatever its status: a stub
# (netbox-declare.sh --stub), or an attested intake fleet-controller has not bound, which the
# Talos root and the UniFi root have nothing to give.
#
#   netbox-export.sh                 write the file
#   netbox-export.sh --check [file]  exit 1 and print the diff if the file (default: the
#                                    committed one) differs from NetBox, or if NetBox's node
#                                    addresses are outside K8S_NODE_CIDR, shared, or leave
#                                    API_SERVER_IP in the cluster topology without a node
#   netbox-export.sh --json          the same machines as JSON, each with its primary address
#
# NetBox access is scripts/lib/netbox.sh's environment.
set -euo pipefail
shopt -s inherit_errexit

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly root
# shellcheck source=scripts/lib/netbox.sh
source "$root/scripts/lib/netbox.sh"

inventory="$root/clusters/folly/inventory/machines.yaml"
readonly cluster="${INVENTORY_TOPOLOGY:-$root/clusters/folly/config/cluster-topology.json}"

usage() {
  echo "usage: $0 [--check [file] | --json]" >&2
  exit 64
}

# Each machine in the inventory's field names, keyed by name, with `address` from NetBox's
# primary IPv4 and its BMC from the OOB address. The node's NIC is its first physical interface with a primary MAC, and its
# switch port is the number of the switch interface its cable reaches.
machines_json() {
  local devices interfaces
  devices="$(nb_list "dcim/devices/?site=folly&role=kubernetes-node&status=planned&status=staged&status=active&status=failed")"
  if [[ "$(jq 'length' <<<"$devices")" -eq 0 ]]; then
    echo '{}'
    return
  fi
  interfaces="$(nb_list "dcim/interfaces/?type__n=virtual&$(jq -r 'map("device_id=\(.id)") | join("&")' <<<"$devices")")"
  jq -n --argjson devices "$devices" --argjson interfaces "$interfaces" '
    def choice: if type == "object" then .value else . end;
    def octets: if . == null then [256] else split("/")[0] | split(".") | map(tonumber) end;
    $devices
    | map(select(. as $d | $d.serial != "" and ($d.custom_fields.talos_class | choice) != null
        and any($interfaces[]; .device.id == $d.id and .primary_mac_address != null)))
    | sort_by((.primary_ip4.address | octets), .name)
    | map(. as $d
      | ([$interfaces[] | select(.device.id == $d.id and .primary_mac_address != null)] | sort_by(.id) | first) as $nic
      | {key: $d.name, value: {
          model: $d.device_type.model,
          sku: $d.custom_fields.sku,
          serial: (if $d.serial == "" then null else $d.serial end),
          bios: $d.custom_fields.bios_version,
          mac: ($nic.primary_mac_address.mac_address // null | if . then ascii_downcase else . end),
          switch_port: ([$nic.link_peers[]?.name | capture("^Port (?<n>[0-9]+)$").n | tonumber] | first),
          disk: $d.custom_fields.install_disk,
          tpm: $d.custom_fields.tpm_version,
          amt: $d.custom_fields.amt,
          secure_boot: $d.custom_fields.secure_boot_expected,
          class: ($d.custom_fields.talos_class | choice),
          status: $d.status.value,
          address: ($d.primary_ip4.address // null | if . then split("/")[0] else . end),
          bmc: ({type: ($d.custom_fields.bmc_type | choice)} as $b
            | $b + {address: (($d.oob_ip.address // null | if . then split("/")[0] else . end)
              // (if $b.type == "amt" then ($d.primary_ip4.address // null | if . then split("/")[0] else . end) else null end))}),
          ek_hash: $d.custom_fields.ek_hash,
          ek_hash_ecc: $d.custom_fields.ek_hash_ecc
        }})
    | from_entries'
}

render() {
  cat <<'EOF'
# Generated by `mise run netbox:export` from NetBox (https://capsule.<tailnet>);
# never edit it by hand. Change the device in NetBox, run the export, and open
# a pull request with the result. `mise run netbox:check` fails on a difference.
#
# folly's Kubernetes nodes as hardware: every NetBox device with the role
# kubernetes-node and the status planned, staged, active or failed. status is
# the node's lifecycle state and class its Talos class. address is the primary
# IPv4, and the node's address everywhere; `mise run netbox:check` fails when a
# node's is outside K8S_NODE_CIDR in ../config/cluster-topology.json or is
# shared, or when API_SERVER_IP there is no node's. bmc is the out-of-band management: its
# type, and its address, which is the node's own for AMT unless NetBox holds an
# OOB address.
#
# Read by terraform/network/unifi/folly (reservations, MAB users, mab_ports),
# clusters/folly/talos (install disk, tpm_nodes) and the render scripts. Like
# clients.yaml, a change here alone gets no Atlantis autoplan: comment
# `atlantis plan -d <root>` for each root above.
#
# tpm is the TPM spec version, or null; only 2.0 seals disks and attests.
# secure_boot is the firmware state the node is expected to boot in.
# ek_hash and ek_hash_ecc are the pinned RSA and ECC endorsement key hashes, or null.
EOF
  jq '{machines: .}' <<<"$1" | yq -P -p json
}

# addresses_valid: a node (staged, active or failed) has an address in K8S_NODE_CIDR, no two
# nodes share one, and API_SERVER_IP is a node's. Planned nodes are not checked.
addresses_valid() { # <machines json>
  local problems
  problems="$(jq -rn --argjson export "$1" --slurpfile topology "$cluster" '
    def ip: split(".") | map(tonumber) | reduce .[] as $o (0; . * 256 + $o);
    $topology[0].data as $t
    | ($t.K8S_NODE_CIDR | split("/")) as [$net, $len]
    | pow(2; 32 - ($len | tonumber)) as $size
    | ($export | to_entries | map(select(.value.status != "planned"))) as $nodes
    | ([$nodes[] | select(.value.address == null) | "\(.key): no address in NetBox"]
      + [$nodes[] | select(.value.address != null
          and ((((.value.address | ip) / $size) | floor) != ((($net | ip) / $size) | floor)))
          | "\(.key): \(.value.address) is outside K8S_NODE_CIDR \($t.K8S_NODE_CIDR)"]
      + [$nodes | group_by(.value.address)[] | select(length > 1 and .[0].value.address != null)
          | "\(map(.key) | join(" and ")) share \(.[0].value.address)"]
      + (if ($nodes | any(.value.address == $t.API_SERVER_IP)) then [] else ["API_SERVER_IP \($t.API_SERVER_IP) is not a node address"] end))[]')" || {
    echo "cannot check node addresses in ${cluster#"$root"/} against NetBox" >&2
    return 2
  }
  if [[ -n "$problems" ]]; then
    printf '%s\n' "$problems" >&2
    echo "node addresses in NetBox disagree with ${cluster#"$root"/}" >&2
    return 1
  fi
}

nb_init
case "${1:-}" in
  "")
    [[ $# -eq 0 ]] || usage
    machines="$(machines_json)"
    rendered="$(render "$machines")"
    printf '%s\n' "$rendered" >"$inventory"
    echo "wrote ${inventory#"$root"/}"
    ;;
  --check)
    [[ $# -le 2 ]] || usage
    file="${2:-$inventory}"
    machines="$(machines_json)"
    rendered="$(render "$machines")"
    failed=0
    if ! diff -u --label "${file#"$root"/}" --label NetBox "$file" - <<<"$rendered"; then
      echo "${file#"$root"/} differs from NetBox; run mise run netbox:export" >&2
      failed=1
    fi
    addresses_valid "$machines" || failed=1
    exit "$failed"
    ;;
  --json)
    [[ $# -eq 1 ]] || usage
    machines_json
    ;;
  *) usage ;;
esac
